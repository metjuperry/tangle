import { test, expect } from '../../web/node_modules/@playwright/test'

test('tie by keyboard, label, note, cut and re-tie survive sync', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Development key').fill('tangle-browser-test-key-not-a-secret')
  await page.getByRole('button', { name: 'Unlock Tangle' }).click()
  await page.getByRole('button', { name: /example\/repo #49,/ }).click()
  await page.getByRole('button', { name: 'Tie a string', exact: true }).click()
  await page.getByRole('button', { name: /example\/tools #197,/ }).focus()
  await page.keyboard.press('Enter')
  await page.getByLabel('Label the string').fill('November release')
  await page.getByRole('button', { name: 'Save label' }).click()
  await expect(page.locator('.handwriting').filter({ hasText: 'November release' })).toBeVisible()
  await page.getByLabel('Add a note').fill('Keep this context')
  await page.getByRole('button', { name: 'Pin it' }).click()
  await expect(page.locator('.handwriting').filter({ hasText: 'Keep this context' })).toBeVisible()
  await page.getByRole('button', { name: 'Cut the string' }).click()
  await expect(page.getByRole('button', { name: 'Re-tie string' })).toBeVisible()
  await page.getByRole('button', { name: 'Sync', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Re-tie string' })).toBeVisible()
  await page.getByRole('button', { name: 'Re-tie string' }).click()
  await expect(page.getByRole('button', { name: 'Cut the string' })).toBeVisible()
})
test('create sticky, tie cards and move a card persistently', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Development key').fill('tangle-browser-test-key-not-a-secret')
  await page.getByRole('button', { name: 'Unlock Tangle' }).click()
  await page.getByLabel('New sticky title').fill('Customer demo')
  await page.getByRole('button', { name: 'Create sticky' }).click()
  await expect(page.getByLabel('Sticky title')).toHaveValue('Customer demo')
  await page.getByRole('button', { name: 'Tie a string', exact: true }).click()
  await page.getByRole('button', { name: /example\/repo #49,/ }).click()
  await expect(page.getByLabel('Label the string')).toBeVisible()
  await page.getByRole('button', { name: 'Sticky: Customer demo' }).click()
  await page.getByRole('button', { name: 'Tie a string', exact: true }).click()
  await page.getByRole('button', { name: /example\/tools #198,/ }).click()
  await expect(page.getByLabel('Label the string')).toBeVisible()
  const card = page.locator('[data-testid="card-example/repo#49"]')
  const box = await card.boundingBox()
  if (!box) throw new Error('Card missing')
  await page.mouse.move(box.x + 35, box.y + 50)
  await page.mouse.down()
  await page.mouse.move(box.x + 60, box.y + 75, { steps: 12 })
  await page.mouse.up()
  await expect.poll(async () => (await (await page.request.get('/api/board')).json()).positions.length).toBeGreaterThan(0)
  await page.reload()
  await expect(page.locator('.sticky-node')).toContainText('Customer demo')
  const board = await (await page.request.get('/api/board')).json()
  const saved = board.positions.find((p: { nodeRef: string }) => p.nodeRef === 'pr:example/repo#49')
  expect(saved).toBeTruthy()
  const node = page.locator('.react-flow__node').filter({ has: page.locator('[data-testid="card-example/repo#49"]') })
  const zone = page.locator('.react-flow__node[data-id="zone:example/repo"]')
  await expect.poll(async () => {
    const position = await node.evaluate(el => { const m = new DOMMatrix(getComputedStyle(el).transform); return { x: m.m41, y: m.m42 } })
    const parent = await zone.evaluate(el => { const m = new DOMMatrix(getComputedStyle(el).transform); return { x: m.m41, y: m.m42 } })
    return { x: position.x - parent.x, y: position.y - parent.y }
  }).toEqual({ x: saved.x, y: saved.y })
})
test('drag pin to pin creates a labelled navy tie', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Development key').fill('tangle-browser-test-key-not-a-secret')
  await page.getByRole('button', { name: 'Unlock Tangle' }).click()
  const source = page.locator('[data-testid="card-example/templates#199"] .react-flow__handle.source')
  const target = page.locator('[data-testid="card-example/tools#196"] .react-flow__handle.target')
  const a = await source.boundingBox(), b = await target.boundingBox()
  if (!a || !b) throw new Error('Pins missing')
  await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2)
  await page.mouse.down()
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 15 })
  await page.mouse.up()
  await expect(page.getByLabel('Label the string')).toBeVisible()
  await page.getByLabel('Label the string').fill('Shared delivery')
  await page.getByRole('button', { name: 'Save label' }).click()
  await expect(page.locator('.handwriting').filter({ hasText: 'Shared delivery' })).toBeVisible()
})
